-- ============================================
-- ESQUEMA DE LA BASE DE DATOS (PostgreSQL / Supabase)
-- ============================================
-- Se ejecuta sobre la base de datos "postgres" del proyecto de Supabase.
-- Los nombres van en minúsculas porque así los espera el backend
-- (ver backend/Models/*.cs) y sin esquema: las tablas se crean en el
-- esquema activo. En Supabase es "public"; las pruebas automatizadas
-- ejecutan este mismo archivo sobre el esquema "test".

-- ============================================
-- TABLA: especialidad
-- ============================================
-- Contiene las áreas médicas (Cardiología, etc.)

create table especialidad (
    id_especialidad integer generated by default as identity primary key,
    nombre          varchar(100) not null
);

-- ============================================
-- TABLA: paciente
-- ============================================
-- Representa a cada paciente del hospital

create table paciente (
    id_paciente      integer generated by default as identity primary key,
    nombre           varchar(50) not null,
    apellido         varchar(50) not null,
    fecha_nacimiento date,
    telefono         varchar(20),
    email            varchar(100)
);

-- ============================================
-- TABLA: doctor
-- ============================================
-- Relacionado con especialidad

create table doctor (
    id_doctor       integer generated by default as identity primary key,
    nombre          varchar(50) not null,
    apellido        varchar(50) not null,
    id_especialidad integer not null references especialidad (id_especialidad)
);

create index doctor_id_especialidad_idx on doctor (id_especialidad);

-- ============================================
-- TABLA: cita
-- ============================================
-- Conecta paciente y doctor

create table cita (
    id_cita     integer generated by default as identity primary key,
    id_paciente integer not null references paciente (id_paciente),
    id_doctor   integer not null references doctor (id_doctor),
    fecha       date not null,
    hora        time not null,
    motivo      text
);

create index cita_id_paciente_idx on cita (id_paciente);
create index cita_id_doctor_idx   on cita (id_doctor);
create index cita_fecha_idx       on cita (fecha);

-- ============================================
-- TABLA: consulta
-- ============================================
-- Resultado de la cita (relación 1:1 → id_cita es único)

create table consulta (
    id_consulta   integer generated by default as identity primary key,
    id_cita       integer not null unique references cita (id_cita),
    diagnostico   text,
    observaciones text
);

-- ============================================
-- SEGURIDAD (Supabase)
-- ============================================
-- Supabase expone el esquema "public" por su API REST automática.
-- Con RLS activado y sin políticas, esa API no puede leer ni escribir
-- estas tablas. El backend de ASP.NET no se ve afectado: se conecta
-- directamente a Postgres como dueño de las tablas.

alter table especialidad enable row level security;
alter table paciente     enable row level security;
alter table doctor       enable row level security;
alter table cita         enable row level security;
alter table consulta     enable row level security;
